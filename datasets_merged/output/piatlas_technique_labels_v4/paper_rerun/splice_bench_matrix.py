#!/usr/bin/env python3
"""Replace the data rows of sections/tab_benchmark_matrix.tex (from the ASB row through the
"All curated" row) with bench_matrix_rows.tex, and update the provenance comment on line 1."""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
TAB = os.path.join(HERE, "..", "..", "..", "..", "paper_draft", "PIAtlas_final", "sections", "tab_benchmark_matrix.tex")
s = open(TAB).read()
rows = open(os.path.join(HERE, "bench_matrix_rows.tex")).read().rstrip("\n")
start = s.index("ASB~\\cite{zhang2024asb}")
end = s.index("\\\\", s.index("All curated (non-LLMail)")) + 2
s = s[:start] + rows + s[end:]
s = re.sub(r"^% Auto-generated from .*$",
           "% Auto-generated by gen_bench_matrix.py from piatlas_v4_curated_4663.json, datasets_noll.json and "
           "piatlas_v4_llmail_4000.json (technique-level labels, current listing).", s, count=1, flags=re.M)
open(TAB, "w").write(s)
print("spliced", rows.count("\\\\"), "rows into", os.path.normpath(TAB))
